const DrvSpiConfig_t kBspSpiConfigTable[BSP_SPI_CH_COUNT] = {
    [BSP_SPI_CH_DAC] = {
        .hwInstanceId  = 0U, /* MCU-A: SPI0; on MCU-B board, DAC is wired to SPI1 (1U) */
        .maxClock_hz   = { .hz = 6000000U },
        .clockMode     = DRV_SPI_MODE_0,
        .csPortId      = 0U, /* MCU-A: GPIOA; on MCU-B board, CS is on GPIOC (2U) */
        .csPin         = 4U, /* MCU-A: PA4; on MCU-B board, CS is on PC2 (2U) */
        .isCsActiveLow = true
    }
};

_Static_assert(ARRAY_LEN(kBspSpiConfigTable) == (size_t)BSP_SPI_CH_COUNT,
               "kBspSpiConfigTable size must match BspSpiChannel_e count");

