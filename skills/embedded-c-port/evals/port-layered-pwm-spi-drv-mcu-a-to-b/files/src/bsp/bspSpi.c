Status_e bspSpi_Init(void) {
    return drvSpi_Init(kBspSpiConfigTable, (size_t)BSP_SPI_CH_COUNT);
}

Status_e bspSpi_DacTransferFrame(uint16_t dacFrameWord,
                                 uint16_t * const outLoopbackWord) {
    uint16_t discardedRx = 0U;
    uint16_t * const rxTarget = (outLoopbackWord != NULL) ? outLoopbackWord : &discardedRx;
    return drvSpi_TransferWord((size_t)BSP_SPI_CH_DAC, dacFrameWord, rxTarget);
}
